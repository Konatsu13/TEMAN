-- TEMAN — Global Chat + AI mention
-- Review this migration before running it in Supabase SQL Editor.
--
-- This adds one new table (public.chat_messages). It does not rename or drop
-- any existing table/column. The table is intentionally a single global room
-- for every active workspace user; per-competition chat remains out of scope.

create table if not exists public.chat_messages (
  id uuid primary key default gen_random_uuid(),
  author_id uuid references public.profiles(id) on delete set null,
  content text not null,
  is_ai boolean not null default false,
  reply_to_id uuid references public.chat_messages(id) on delete cascade,
  edited_at timestamptz,
  created_at timestamptz not null default now(),
  constraint chat_messages_content_check check (
    (is_ai = false and char_length(btrim(content)) between 1 and 2000)
    or (is_ai = true and char_length(btrim(content)) between 1 and 4000)
  ),
  constraint chat_messages_ai_shape_check check (
    is_ai = false
    or (is_ai = true and author_id is null and reply_to_id is not null)
  )
);

comment on table public.chat_messages is
  'Single global chat room for active TEMAN workspace members, including persisted AI replies.';
comment on column public.chat_messages.is_ai is
  'True when the message was generated by the chat-ai Edge Function.';
comment on column public.chat_messages.reply_to_id is
  'For AI messages, the user message that mentioned @ai. One AI reply per message.';

create index if not exists chat_messages_created_at_idx
  on public.chat_messages (created_at desc);

create unique index if not exists chat_messages_ai_reply_unique_idx
  on public.chat_messages (reply_to_id)
  where is_ai = true;

alter table public.chat_messages enable row level security;

-- Authenticated users get the table privileges; RLS below decides which rows.
grant select, insert, update, delete on public.chat_messages to authenticated;

-- Everyone active in the workspace can read the global room.
drop policy if exists "chat_messages_select_active" on public.chat_messages;
create policy "chat_messages_select_active"
  on public.chat_messages
  for select
  to authenticated
  using (public.is_active_user(auth.uid()));

-- Members may post as themselves. The chat-ai Edge Function posts an AI reply
-- using the caller's JWT, so an AI row is allowed only as a reply to a real
-- user message that actually mentions @ai or @teman.
--
-- The helper is SECURITY DEFINER so the policy can inspect the parent row
-- without recursively evaluating chat_messages policies. It only returns a
-- boolean for the caller's own message; the caller cannot pass another user id.
drop function if exists public.is_valid_chat_ai_reply(uuid, uuid);

create or replace function public.is_valid_chat_ai_reply(p_reply_to_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.chat_messages parent
    where parent.id = p_reply_to_id
      and parent.is_ai = false
      and parent.author_id = auth.uid()
      and parent.content ~* '(^|[^a-zA-Z0-9_@/])@(ai|teman)($|[^a-zA-Z0-9_.-]|\.($|[^a-zA-Z0-9_-]))'
  );
$$;

revoke all on function public.is_valid_chat_ai_reply(uuid) from public;
grant execute on function public.is_valid_chat_ai_reply(uuid) to authenticated;

drop policy if exists "chat_messages_insert_active" on public.chat_messages;
create policy "chat_messages_insert_active"
  on public.chat_messages
  for insert
  to authenticated
  with check (
    public.is_active_user(auth.uid())
    and (
      (is_ai = false and author_id = auth.uid() and char_length(btrim(content)) between 1 and 2000)
      or (
        is_ai = true
        and author_id is null
        and reply_to_id is not null
        and public.is_valid_chat_ai_reply(reply_to_id)
      )
    )
  );

-- Chat mentions have no task/competition context. This SECURITY DEFINER helper
-- lets an active member create mention notifications for other active members,
-- but only from a message the caller actually authored. Recipients are resolved
-- from the stored message content, never from client-supplied user ids.
create or replace function public.notify_chat_mentions(p_message_id uuid)
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_content text;
  v_author_name text;
  v_count integer := 0;
begin
  if v_user_id is null or not public.is_active_user(v_user_id) then
    raise exception 'Akun tidak aktif.' using errcode = '42501';
  end if;

  select content
    into v_content
  from public.chat_messages
  where id = p_message_id
    and author_id = v_user_id
    and is_ai = false;

  if v_content is null then
    return 0;
  end if;

  select coalesce(nullif(btrim(full_name), ''), 'Anggota')
    into v_author_name
  from public.profiles
  where id = v_user_id;

  insert into public.notifications (user_id, actor_id, type, title, body)
  select recipient.id,
         v_user_id,
         'mention'::public.notification_type,
         v_author_name || ' menyebut Anda di Global Chat',
         left(v_content, 150)
  from public.profiles recipient
  where recipient.is_active = true
    and recipient.id <> v_user_id
    and exists (
      select 1
      from regexp_matches(
        v_content,
        '(^|[^a-zA-Z0-9_@/])@([a-zA-Z0-9_]+(?:\.[a-zA-Z0-9_]+)*)',
        'g'
      ) as mention(match)
      where lower(mention.match[2]) = lower(recipient.username)
    );

  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

revoke all on function public.notify_chat_mentions(uuid) from public;
grant execute on function public.notify_chat_mentions(uuid) to authenticated;

-- Authors can edit their own human messages. AI messages are immutable.
drop policy if exists "chat_messages_update_own" on public.chat_messages;
create policy "chat_messages_update_own"
  on public.chat_messages
  for update
  to authenticated
  using (
    public.is_active_user(auth.uid())
    and is_ai = false
    and author_id = auth.uid()
  )
  with check (
    public.is_active_user(auth.uid())
    and is_ai = false
    and author_id = auth.uid()
    and char_length(btrim(content)) between 1 and 2000
  );

-- Authors can delete their own messages; Owner can moderate the room.
drop policy if exists "chat_messages_delete_own_or_owner" on public.chat_messages;
create policy "chat_messages_delete_own_or_owner"
  on public.chat_messages
  for delete
  to authenticated
  using (
    public.is_active_user(auth.uid())
    and (
      (is_ai = false and author_id = auth.uid())
      or public.is_owner(auth.uid())
    )
  );

-- Realtime INSERT/UPDATE/DELETE events for the global room.
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'chat_messages'
  ) then
    alter publication supabase_realtime add table public.chat_messages;
  end if;
end
$$;

notify pgrst, 'reload schema';
